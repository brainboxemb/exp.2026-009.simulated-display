static bool glyph_descriptor_get(
        const lv_font_t *font,
        lv_font_glyph_dsc_t *descriptor,
        uint32_t letter,
        uint32_t letter_next) {
    LV_UNUSED(font);
    LV_UNUSED(letter_next);

    if (letter < FIRST_CODEPOINT
            || letter > LAST_CODEPOINT) {
        return false;
    }

    descriptor->adv_w = GLYPH_WIDTH;
    descriptor->box_w = GLYPH_WIDTH;
    descriptor->box_h = GLYPH_HEIGHT;
    descriptor->ofs_x = 0;
    descriptor->ofs_y = 0;
    descriptor->stride = 1;
    descriptor->format = LV_FONT_GLYPH_FORMAT_A1;
    descriptor->is_placeholder = false;
    descriptor->gid.index =
            letter - FIRST_CODEPOINT;

    return true;
}

static const void *glyph_bitmap_get(
        lv_font_glyph_dsc_t *descriptor,
        lv_draw_buf_t *draw_buffer) {
    if (descriptor->gid.index >= GLYPH_COUNT) {
        return NULL;
    }

    const uint8_t *bitmap =
            glyph_bitmap[descriptor->gid.index];

    if (descriptor->req_raw_bitmap) {
        return bitmap;
    }

    if (draw_buffer == NULL) {
        return NULL;
    }

    memset(
            draw_buffer->data,
            0,
            draw_buffer->data_size);

    for (uint32_t y = 0;
            y < GLYPH_HEIGHT;
            y++) {
        for (uint32_t x = 0;
                x < GLYPH_WIDTH;
                x++) {
            draw_buffer->data[
                    y * draw_buffer->header.stride
                    + x] =
                    (bitmap[y]
                            & (0x80u >> x))
                    != 0
                    ? 0xffu
                    : 0x00u;
        }
    }

    return draw_buffer;
}

