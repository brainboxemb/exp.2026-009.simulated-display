static bool glyph_descriptor_get(
        const lv_font_t *font,
        lv_font_glyph_dsc_t *descriptor,
        uint32_t letter,
        uint32_t letter_next) {
    LV_UNUSED(font);
    LV_UNUSED(letter_next);

    if (letter < FIRST_CODEPOINT
            || letter > LAST_CODEPOINT) {
        return false;
    }

    const VbzGlyph *glyph =
            &glyphs[letter - FIRST_CODEPOINT];

    descriptor->adv_w = glyph->advance;
    descriptor->box_w = glyph->width;
    descriptor->box_h = glyph->height;
    descriptor->ofs_x = glyph->x_offset;

    /*
     * GFX yOffset is measured downwards from the text cursor. With a 12-pixel
     * line, convert that top offset to LVGL's bottom-relative ofs_y.
     */
    descriptor->ofs_y =
            FONT_LINE_HEIGHT
            - glyph->height
            - glyph->y_offset;

    descriptor->stride = glyph->width;
    descriptor->format = LV_FONT_GLYPH_FORMAT_A8;
    descriptor->is_placeholder = false;
    descriptor->gid.index =
            letter - FIRST_CODEPOINT;

    return true;
}

static const void *glyph_bitmap_get(
        lv_font_glyph_dsc_t *descriptor,
        lv_draw_buf_t *draw_buffer) {
    if (descriptor->gid.index >= GLYPH_COUNT
            || draw_buffer == NULL) {
        return NULL;
    }

    const VbzGlyph *glyph =
            &glyphs[descriptor->gid.index];

    memset(
            draw_buffer->data,
            0,
            draw_buffer->data_size);

    if (glyph->height == 0) {
        return draw_buffer;
    }

    const uint8_t height =
            (uint8_t)descriptor->box_h;

    for (uint32_t y = 0;
            y < height;
            y++) {
        const uint32_t source_y =
                (y * glyph->height)
                / height;

        const size_t row_offset =
                glyph->bitmap_offset
                + source_y * SOURCE_ROW_BYTES;

        const uint16_t row =
                ((uint16_t)bitmap[row_offset] << 8u)
                | bitmap[row_offset + 1u];

        for (uint32_t x = 0;
                x < glyph->width;
                x++) {
            draw_buffer->data[
                    y * draw_buffer->header.stride
                    + x] =
                    (row & (0x8000u >> x))
                    != 0
                    ? 0xffu
                    : 0x00u;
        }
    }

    return draw_buffer;
}

