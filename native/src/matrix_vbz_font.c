static bool vbz_glyph_descriptor_get(
        const lv_font_t *font,
        lv_font_glyph_dsc_t *descriptor,
        uint32_t letter,
        uint32_t letter_next) {
    LV_UNUSED(letter_next);

    if (letter < FIRST_CODEPOINT
            || letter > LAST_CODEPOINT) {
        return false;
    }

    const VbzGlyph *glyph =
            &vbz_glyphs[letter - FIRST_CODEPOINT];
    const bool expanded =
            font == &matrix_font_vbz_10;

    descriptor->adv_w = glyph->advance;
    descriptor->box_w =
            glyph->source_height == 0
                    ? 0
                    : glyph->source_width;
    descriptor->box_h =
            glyph->source_height == 0
                    ? 0
                    : expanded
                            ? 10
                            : glyph->source_height;
    descriptor->ofs_x = glyph->offset_x;
    descriptor->ofs_y =
            glyph->source_height == 0
                    ? 0
                    : expanded
                            ? 0
                            : glyph->offset_y;
    descriptor->stride =
            (uint16_t)((glyph->source_width + 7u) / 8u);
    descriptor->format = LV_FONT_GLYPH_FORMAT_A1;
    descriptor->is_placeholder = false;
    descriptor->gid.index =
            letter - FIRST_CODEPOINT;

    return true;
}

static bool source_pixel(
        const VbzGlyph *glyph,
        uint32_t x,
        uint32_t y) {
    const uint32_t stride =
            (glyph->source_width + 7u) / 8u;
    const uint32_t index =
            glyph->bitmap_offset
            + y * stride
            + x / 8u;
    const uint8_t mask =
            (uint8_t)(0x80u >> (x % 8u));

    return (vbz_bitmap[index] & mask) != 0;
}

static const void *vbz_glyph_bitmap_get(
        lv_font_glyph_dsc_t *descriptor,
        lv_draw_buf_t *draw_buffer) {
    if (descriptor->gid.index >= GLYPH_COUNT) {
        return NULL;
    }

    const VbzGlyph *glyph =
            &vbz_glyphs[descriptor->gid.index];

    if (glyph->source_height == 0) {
        return NULL;
    }

    if (draw_buffer == NULL) {
        return NULL;
    }

    memset(
            draw_buffer->data,
            0,
            draw_buffer->data_size);

    const bool expanded =
            descriptor->resolved_font
                    == &matrix_font_vbz_10;
    const uint32_t target_height =
            expanded
                    ? 10u
                    : glyph->source_height;

    for (uint32_t y = 0;
            y < target_height;
            y++) {
        const uint32_t source_y =
                expanded
                        ? (y * glyph->source_height) / target_height
                        : y;

        for (uint32_t x = 0;
                x < glyph->source_width;
                x++) {
            draw_buffer->data[
                    y * draw_buffer->header.stride
                    + x] =
                    source_pixel(
                            glyph,
                            x,
                            source_y)
                    ? 0xffu
                    : 0x00u;
        }
    }

    return draw_buffer;
}

