bool custom_bitmap_digit_lookup(uint8_t digit, CustomBitmap *bitmap) {
    if (digit >= CUSTOM_BITMAP_DIGIT_COUNT || bitmap == NULL) {
        return false;
    }

    bitmap->width = DIGIT_WIDTH;
    bitmap->height = DIGIT_HEIGHT;
    bitmap->bands = DIGITS[digit];
    return true;
}
